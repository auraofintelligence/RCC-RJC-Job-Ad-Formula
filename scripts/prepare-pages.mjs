import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root = path.resolve(fileURLToPath(new URL('../', import.meta.url)));
const checking = process.argv.includes('--check');
const read = (relative) => readFile(path.join(root, relative), 'utf8');
const publicUrl = 'https://auraofintelligence.github.io/RCC-RJC-Job-Ad-Formula/';
const index = await read('dist/index.html');
const licence = await read('LICENCE.md');
const escape = (value) => value.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
const paragraphs = licence.trim().split(/\r?\n\s*\r?\n/).map((block) => {
  if (block.startsWith('# ')) return `<h1>${escape(block.slice(2))}</h1>`;
  if (block.startsWith('## ')) return `<h2>${escape(block.slice(3))}</h2>`;
  if (block.startsWith('- ')) return `<ul>${block.split(/\r?\n/).map((line)=>`<li>${escape(line.replace(/^- /,''))}</li>`).join('')}</ul>`;
  return `<p>${escape(block).replace(/\r?\n/g,'<br>')}</p>`;
}).join('\n');
const licencePage = `<!doctype html>
<html lang="en-AU"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Public Source Licence · Job Ad Formula</title><link rel="icon" type="image/x-icon" href="assets/favicon.ico"><link rel="stylesheet" href="styles.css">
<style>.licence{max-width:850px;padding-block:45px 70px}.licence h1{font:750 clamp(29px,5vw,43px)/1.15 Manrope,system-ui,sans-serif;letter-spacing:-1.3px;margin:24px 0}.licence h2{font:700 21px Manrope,system-ui,sans-serif;margin:32px 0 14px}.licence p,.licence li{font-size:14px;line-height:1.8;overflow-wrap:anywhere}.licence ul{padding-left:22px}.licence li{margin:8px 0}.licence .back{font-size:13px}.licence .licence-download{font-size:12px;color:var(--muted);border-top:1px solid var(--line);margin-top:35px;padding-top:20px}</style></head>
<body><main class="shell licence"><a class="back" href="./">← Back to Job Ad Formula</a>${paragraphs}<p class="licence-download"><a href="LICENCE.md">Download the licence as Markdown</a> · <a href="https://github.com/auraofintelligence/RCC-RJC-Job-Ad-Formula">Original repository</a></p></main></body></html>\n`;

// GitHub Pages currently publishes main's root. Keep a real application entry
// there while dist remains the canonical static source for both hosting routes.
const githubIndex = index.replace('<head>', '<head>\n  <!-- Generated by scripts/prepare-pages.mjs from dist/index.html. -->\n  <base href="./dist/">')
  .replaceAll('href="#','href="../#').replace('class="brand" href="./"','class="brand" href="../"');
const robots = `User-agent: *\nAllow: /\nSitemap: ${publicUrl}sitemap.xml\n`;
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>${publicUrl}</loc></url>\n  <url><loc>${publicUrl}dist/licence.html</loc></url>\n</urlset>\n`;
const outputs = new Map([
  ['index.html',githubIndex],['.nojekyll',''],['robots.txt',robots],['sitemap.xml',sitemap],
  ['dist/robots.txt',robots],['dist/sitemap.xml',sitemap],['dist/LICENCE.md',licence],['dist/licence.html',licencePage],
]);
for (const [relative, content] of outputs) {
  if (checking) {
    let actual; try { actual = await read(relative); } catch { throw new Error(`Missing publishing file: ${relative}. Run npm run prepare-pages.`); }
    if (actual !== content) throw new Error(`Stale publishing file: ${relative}. Run npm run prepare-pages.`);
  } else await writeFile(path.join(root,relative),content,'utf8');
}
for (const asset of ['favicon.ico','favicon-32.png','favicon-192.png','apple-touch-icon.png']) {
  const data = await readFile(path.join(root,'dist/assets',asset));
  if (!data.length) throw new Error(`Empty favicon asset: ${asset}`);
}
const rootBase = new URL('./dist/', publicUrl);
for (const relative of ['styles.css','app.mjs','assets/favicon.ico','licence.html']) {
  const target = new URL(relative,rootBase);
  if (!target.pathname.startsWith('/RCC-RJC-Job-Ad-Formula/dist/')) throw new Error(`Incorrect Pages asset path: ${relative}`);
  await readFile(path.join(root,'dist',relative));
}
console.log(checking ? 'Publishing entry, licence, robots, sitemap and icons checked.' : 'Publishing entry, licence, robots and sitemap prepared.');
